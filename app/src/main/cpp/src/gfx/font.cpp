static const int NG = sizeof(GL) / sizeof(GL[0]);
static Texture2D tex; static bool ok = false;

static int fold(int cp) {
    if (cp >= 'a' && cp <= 'z') return cp - 32;
    if (cp >= 0x430 && cp <= 0x44F) cp -= 0x20;
    if (cp == 0x451) cp = 0x401;
    switch (cp) {   // кириллица, неотличимая от латиницы
        case 0x410: return 'A'; case 0x412: return 'B'; case 0x415: return 'E'; case 0x41A: return 'K'; case 0x41C: return 'M';
        case 0x41D: return 'H'; case 0x41E: return 'O'; case 0x420: return 'P'; case 0x421: return 'C'; case 0x422: return 'T'; case 0x425: return 'X';
    }
    return cp;
}
static int findGlyph(int cp) { cp = fold(cp); for (int i = 0; i < NG; i++) if (GL[i].cp == cp) return i; return 0; }

void init() {
    Image img = GenImageColor(16 * 8, ((NG + 15) / 16) * 8, BLANK);
    Color* px = (Color*)img.data;
    for (int i = 0; i < NG; i++) {
        int gx = (i % 16) * 8, gy = (i / 16) * 8;
        for (int r = 0; r < 7; r++) for (int c = 0; c < 5; c++)
            if (GL[i].r[r] & (0x10 >> c)) px[(gy + r) * img.width + gx + c] = WHITE;
    }
    tex = LoadTextureFromImage(img); UnloadImage(img);
    SetTextureFilter(tex, TEXTURE_FILTER_POINT); ok = true;
}
void shutdown() { if (ok) UnloadTexture(tex); ok = false; }

static int next(const char*& s) {      // UTF-8 -> code point
    unsigned char c = (unsigned char)*s++;
    if (c < 0x80) return c;
    if ((c & 0xE0) == 0xC0) { int r = (c & 0x1F) << 6; r |= (*s++ & 0x3F); return r; }
    if ((c & 0xF0) == 0xE0) { int r = (c & 0x0F) << 12; r |= (*s++ & 0x3F) << 6; r |= (*s++ & 0x3F); return r; }
    s += 3; return '?';
}
int width(const char* s) { int n = 0; while (*s) { next(s); n++; } return n * 6 - 1; }
void draw(const char* s, int x, int y, Color c) {
    while (*s) {
        int cp = next(s);
        if (cp != ' ') { int i = findGlyph(cp); DrawTextureRec(tex, {(float)((i % 16) * 8), (float)((i / 16) * 8), 6, 7}, {(float)x, (float)y}, c); }
        x += 6;
    }
}
void drawShadow(const char* s, int x, int y, Color c, Color sh) { draw(s, x + 1, y + 1, sh); draw(s, x, y, c); }
void drawCenter(const char* s, int cx, int y, Color c, bool shadow) {
    int x = cx - width(s) / 2; if (shadow) drawShadow(s, x, y, c, {10, 6, 20, 255}); else draw(s, x, y, c);
}
void drawScaled(const char* s, int x, int y, Color c, int sc) {
    while (*s) {
        int cp = next(s);
        if (cp != ' ') { int i = findGlyph(cp); DrawTexturePro(tex, {(float)((i % 16) * 8), (float)((i / 16) * 8), 6, 7}, {(float)x, (float)y, (float)(6 * sc), (float)(7 * sc)}, {0, 0}, 0, c); }
        x += 6 * sc;
    }
}
int wrap(const char* s, int maxW, int x, int y, Color c, int lineH) {
    std::vector<char> line; int cy = y; const char* p = s;
    char word[96]; int lw = 0; std::vector<char> cur;
    auto flush = [&]() { cur.push_back(0); draw(cur.data(), x, cy, c); cy += lineH; cur.clear(); lw = 0; };
    while (*p) {
        if (*p == '\n') { flush(); p++; continue; }
        int wl = 0; while (p[wl] && p[wl] != ' ' && p[wl] != '\n' && wl < 90) wl++;
        memcpy(word, p, wl); word[wl] = 0; p += wl; if (*p == ' ') p++;
        int ww = width(word);
        if (lw > 0 && lw + 6 + ww > maxW) flush();
        if (lw > 0) { cur.push_back(' '); lw += 6; }
        for (int i = 0; i < wl; i++) cur.push_back(word[i]);
        lw += ww + 1;
    }
    if (!cur.empty()) flush();
    return cy - y;
}
